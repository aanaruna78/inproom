"""Collects the tenant-isolation matrix and writes it as markdown when INPROOM_ISOLATION_REPORT is set."""

import os
from pathlib import Path

MATRIX: list[tuple[str, str, str, str]] = []  # (route, attack, expected, observed)


def record(route: str, attack: str, expected: str, observed: str) -> None:
    MATRIX.append((route, attack, expected, observed))


RBAC: list[tuple[str, str, str, str]] = []  # (route, actor, expected, observed)


def record_rbac(route: str, actor: str, expected: str, observed: str) -> None:
    RBAC.append((route, actor, expected, observed))


def _write_rbac_report() -> None:
    target = os.environ.get("INPROOM_RBAC_REPORT")
    if not target or not RBAC:
        return
    rows = sorted(set(RBAC))
    failed = sum(1 for _, _, e, o in rows if e != o)
    lines = [
        "# RBAC route x role matrix (live API)",
        "",
        "Generated by tests/security/test_rbac_matrix.py. Expected outcomes come from the agreed matrix",
        "(tests/test_authz_policy.py EXPECTED), written independently of app/authz/policy.py.",
        "",
        f"Cases: {len(rows)} - passed: {len(rows) - failed} - failed: {failed}",
        "",
        "| Route | Actor | Expected | Observed | Result |",
        "|---|---|---|---|---|",
    ]
    for route, actor, expected, observed in rows:
        verdict = "PASS" if expected == observed else "FAIL"
        lines.append(f"| `{route}` | {actor} | {expected} | {observed} | {verdict} |")
    Path(target).parent.mkdir(parents=True, exist_ok=True)
    Path(target).write_text("\n".join(lines) + "\n")


def pytest_sessionfinish(session, exitstatus):
    _write_rbac_report()
    target = os.environ.get("INPROOM_ISOLATION_REPORT")
    if not target or not MATRIX:
        return
    lines = [
        "# Tenant isolation matrix",
        "",
        "Attacker: tenant B (tenant_admin) using tenant A's identifiers, plus forged/foreign tokens.",
        "",
        "| Route | Attack | Expected | Observed | Result |",
        "|---|---|---|---|---|",
    ]
    for route, attack, expected, observed in sorted(set(MATRIX)):
        verdict = "PASS" if expected == observed else "FAIL"
        lines.append(f"| `{route}` | {attack} | {expected} | {observed} | {verdict} |")
    Path(target).parent.mkdir(parents=True, exist_ok=True)
    Path(target).write_text("\n".join(lines) + "\n")
